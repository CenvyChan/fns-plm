import test from 'node:test';
import assert from 'node:assert/strict';
import { createServer } from 'vite';
import { chromium } from 'playwright';
import { mkdirSync } from 'node:fs';

// Loopback only. Every API response is a fixture; all mutation requests are intercepted.
test('daily dashboard, record pagination and entry stay on scoped local fixtures', async () => {
  const server = await createServer({ root: new URL('..', import.meta.url).pathname, server: { host: '127.0.0.1', port: 0 } });
  await server.listen();
  const browser = await chromium.launch({ headless: true, executablePath: '/usr/bin/chromium', args: ['--no-sandbox'] });
  const evidence = new URL('../../qa-evidence/daily-dashboard/', import.meta.url).pathname;
  mkdirSync(evidence, { recursive: true });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
    const errors = [], requests = [], writes = [];
    page.on('pageerror', error => errors.push(error.message));
    const user = { id: 'fixture-user', email: 'local@example.test', displayName: '本地预览员', role: 'admin', disabled: false, isPlatformAdmin: false, createdAt: '2026-10-21', tenantId: 'fixture-tenant', tenantName: '隔离界面预览', organizationId: 'fixture-org', organizationName: '预览组织', accountId: 'fixture-account', accountName: '预览账套', membershipId: 'fixture-member' };
    const workspace = Object.fromEntries(['tasks','projects','kpiRules','reviews','materials','boms','salesBomSnapshots','documents','projectPhases','projectMilestones','projectEvents','projectEventReviews','projectReports','projectTemplates'].map(key => [key, []]));
    let access = { sales: true, purchase: true, canManage: true, canWrite: true };
    let failAnalysis = false;
    let completeReconciliation = true;
    const reconciliation = () => ({ dailyCoverage: {reportCount:25,totalAmount:10864,coveredAmount:0,coverageRate:0}, monthDifference:{systemAmount:10864,k3Amount:9000,difference:1864,differenceRate:20.71,isComplete:completeReconciliation},yearDifference:{systemAmount:10864,k3Amount:9000,difference:1864,differenceRate:20.71,isComplete:completeReconciliation},k3Allocation:{rowCount:0,originalAmount:0,allocatedAmount:0,remainingAmount:0,overAllocatedAmount:0,crossDateCount:0} });
    const fixtureReports = Array.from({ length: 25 }, (_, i) => ({ id: `r${i}`, type: 'sales', date: '2026-10-21', partyName: `本地客户 ${i + 1}`, partyId: 'p1', documentNo: `LOCAL-${String(i + 1).padStart(3, '0')}`, quantity: i + 1, currency: i % 2 ? 'USD' : 'CNY', originalAmount: 100 + i, exchangeRate: i % 2 ? 7 : 1, amountCny: (100 + i) * (i % 2 ? 7 : 1), note: '', source: 'manual', createdAt: '2026-10-21', createdBy: user.id, createdByName: user.displayName, allocatedAmount: 0, links: [], canEdit: true }));
    const aggregate = rows => ({ count: rows.length, quantity: rows.reduce((a,r) => a + r.quantity,0), amountCny: rows.reduce((a,r) => a + r.amountCny,0) });
    await page.route('**/*', async route => {
      const req = route.request(), url = new URL(req.url());
      if (url.hostname !== '127.0.0.1') return route.abort();
      if (!url.pathname.startsWith('/api/')) return route.continue();
      requests.push({ path: url.pathname, query: url.search, headers: req.headers() });
      if (req.method() !== 'GET') {
        writes.push({ path: url.pathname, method: req.method(), body: req.postDataJSON() });
        if (url.pathname === '/api/daily-reports' && req.method() === 'POST') return route.fulfill({ json: { ...fixtureReports[0], ...req.postDataJSON(), id: 'local-created' } });
        return route.fulfill({ status: 400, json: { message: '测试禁止非预期写入' } });
      }
      let data = {};
      if (url.pathname === '/api/auth/status') data = { setupRequired: false };
      else if (url.pathname === '/api/auth/me') data = { user, scopes: [user] };
      else if (url.pathname === '/api/workspace') data = workspace;
      else if (url.pathname === '/api/daily-reports/summary') data = { access, sales:{daily:aggregate(fixtureReports),reconciliation:reconciliation()},purchase:{daily:{count:0,quantity:0,amountCny:0},reconciliation:reconciliation()}, isMock: true, liveErpConnected: false, reportDate: '2026-10-21', notice: '浏览器本地夹具，非真实业务数据；无 ERP 连接。' };
      else if (url.pathname === '/api/daily-reports') data = { reports: fixtureReports, mockEnabled: true };
      else if (url.pathname === '/api/daily-reports/snapshots') data = { snapshots: [], deliveries: [], corrections: [] };
      else if (url.pathname === '/api/daily-reports/k3-lines') data = { rows: [] };
      else if (url.pathname === '/api/daily-reporting/party-options') data = { parties: [{ id: 'p1', name: url.searchParams.get('kind') === 'supplier' ? '本地供应商' : '本地客户', active: true }], masterDataConfigured: true };
      else if (url.pathname === '/api/daily-reporting/exchange-rates') data = { rates: [{ month: '2026-10', currency: 'USD', targetCurrency: 'CNY', rate: '7' }] };
      else if (url.pathname === '/api/daily-reports/analysis/export.xlsx') return route.fulfill({ contentType: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet', body: Buffer.from('fixture-download') });
      else if (url.pathname === '/api/daily-reports/analysis') {
        if (failAnalysis) return route.fulfill({ status: 503, json: { message: '本地模拟加载失败' } });
        const filters = Object.fromEntries(['type','from','to','partyName','createdBy','currency','source','q'].map(key => [key, url.searchParams.get(key) || '']));
        const rows = filters.partyName === '无匹配' ? [] : fixtureReports;
        data = { reports: rows, filters, summary: { ...aggregate(rows), cnyAmount: rows.filter(r => r.currency === 'CNY').reduce((a,r) => a+r.originalAmount,0), usdAmount: rows.filter(r => r.currency === 'USD').reduce((a,r) => a+r.originalAmount,0) }, dailyTrend: rows.length ? [{period:'2026-10-01',count:2,quantity:3,amountCny:400},{period:'2026-10-09',count:4,quantity:8,amountCny:1200},{period:'2026-10-21',count:19,quantity:314,amountCny:aggregate(rows).amountCny-1600}] : [], monthlyTrend: rows.length ? [{period:'2026-10', ...aggregate(rows)}] : [], counterpartRank: [...rows].sort((a,b) => b.amountCny - a.amountCny || a.partyName.localeCompare(b.partyName)).slice(0,10).map(r => ({label:r.partyName,...aggregate([r])})), options: { people: [{id:user.id,label:user.displayName}] }, mockEnabled:true, notice:'本地界面回归夹具；非真实业务数据。', amountBasis:'人民币按保存金额合计；不重算历史汇率。' };
      }
      return route.fulfill({ json: data });
    });
    const origin = `http://127.0.0.1:${server.httpServer.address().port}`;
    const goto = route => page.goto(`${origin}/?page=${route}&date=2026-10-21`);
    const screenshot = async options => {
      await page.evaluate(() => window.scrollTo(0,0));
      await page.evaluate(() => Promise.all(document.getAnimations().map(a => a.finished.catch(() => {}))));
      await page.screenshot({...options,animations:'disabled'});
    };
    await goto('daily-sales-analysis');
    await page.getByRole('region', {name:'销售统计分析结果', exact:true}).waitFor();
    assert.equal(await page.locator('.dac-card').count(),3);
    assert.equal(await page.locator('.dba-summary strong').count(),5);
    assert.equal(await page.getByRole('button',{name:'新增销售日报',exact:true}).count(),0);
    await page.locator('.dac-details summary').first().click();
    assert.equal(await page.locator('.dac-details').first().locator('tbody tr').count(),3);
    await screenshot({ path:`${evidence}/analysis-desktop.png`, fullPage:true });
    // Draft edits must not change the applied export scope.
    await page.getByLabel('客户名称',{exact:true}).fill('尚未应用');
    const download = page.waitForEvent('download');
    await page.getByRole('button',{name:'导出当前口径 Excel',exact:true}).click();
    await download;
    const exportRequest = requests.findLast(r => r.path.endsWith('export.xlsx'));
    assert.equal(new URLSearchParams(exportRequest.query).get('partyName'),null);
    await page.getByLabel('开始日期',{exact:true}).fill('2026-10-22');
    await page.getByRole('button',{name:'应用筛选',exact:true}).click();
    await page.getByRole('alert').filter({hasText:'开始日期不能晚于结束日期'}).waitFor();
    await page.getByLabel('开始日期',{exact:true}).fill('2026-10-21');
    await page.getByLabel('客户名称',{exact:true}).fill('无匹配');
    await page.getByRole('button',{name:'应用筛选',exact:true}).click();
    await page.locator('.dac-card').first().getByText('当前筛选没有数据。',{exact:true}).first().waitFor();
    assert.equal(await page.locator('.dac-card circle').count(),0);
    await page.getByRole('button',{name:'重置',exact:true}).click();
    await page.locator('.dac-card circle').first().waitFor();
    failAnalysis = true;
    await page.getByRole('button',{name:'刷新当前口径',exact:true}).click();
    await page.getByRole('alert').filter({hasText:'本地模拟加载失败'}).waitFor();
    assert.equal(await page.locator('.dac-card').count(),0);
    failAnalysis = false;
    await page.getByRole('button',{name:'重试',exact:true}).click();
    await page.locator('.dac-card').first().waitFor();
    for (const width of [768,390,360]) {
      await page.setViewportSize({width,height:1000});
      await page.evaluate(() => Promise.all(document.getAnimations().map(a => a.finished.catch(() => {}))));
      assert.equal(await page.locator('.dba').evaluate(n => n.scrollWidth <= n.clientWidth),true,`analysis overflow at ${width}`);
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth),true,`page overflow at ${width}`);
      assert.ok(await page.locator('.sidebar').evaluate(n => n.getBoundingClientRect().right <= 1),`sidebar hidden at ${width}`);
      if (width === 390) await screenshot({path:`${evidence}/analysis-mobile.png`,fullPage:true});
    }
    await page.setViewportSize({width:1440,height:1100});
    await goto('daily-sales');
    const records = page.getByRole('region',{name:'销售日报明细表',exact:true});
    await records.waitFor();
    assert.equal(await records.locator('tbody tr').count(),20);
    await records.getByRole('button',{name:'下一页',exact:true}).first().click();
    assert.equal(await records.locator('tbody tr').count(),5);
    await records.getByLabel('每页条数',{exact:true}).first().selectOption('10');
    assert.equal(await records.locator('tbody tr').count(),10);
    await records.getByLabel('跳转页码',{exact:true}).first().fill('3');
    await records.getByRole('button',{name:'跳转',exact:true}).first().click();
    assert.equal(await records.locator('tbody tr').count(),5);
    assert.match(await page.locator('.dba-summary').innerText(),/25/);
    await records.getByRole('button',{name:'首页',exact:true}).first().click();
    await screenshot({path:`${evidence}/records-desktop.png`,fullPage:true});
    await page.setViewportSize({width:390,height:1000});
    await screenshot({path:`${evidence}/records-mobile.png`,fullPage:true});
    assert.equal(await page.locator('.dba').evaluate(n => n.scrollWidth <= n.clientWidth),true);
    await page.setViewportSize({width:1440,height:1100});
    await page.getByRole('button',{name:'新增销售日报',exact:true}).click();
    const form = page.locator('form.dr-form');
    await form.waitFor();
    await form.getByLabel('客户 / 供应商').selectOption('p1');
    await form.getByLabel('数量',{exact:true}).fill('15');
    await form.getByLabel('原币金额',{exact:true}).fill('123.45');
    await form.getByLabel('单据编号',{exact:true}).fill('LOCAL-NEW');
    await screenshot({path:`${evidence}/entry-desktop.png`,fullPage:true});
    await page.setViewportSize({width:390,height:1000});
    await screenshot({path:`${evidence}/entry-mobile.png`,fullPage:true});
    assert.equal(await page.locator('.dr-section').evaluate(n => n.scrollWidth <= n.clientWidth),true);
    await form.getByRole('button',{name:'保存日报',exact:true}).click();
    await page.getByRole('status').filter({hasText:'日报已保存。'}).waitFor();
    await screenshot({path:`${evidence}/local-save-confirmation.png`,fullPage:true});
    assert.equal(writes.length,1);
    assert.equal(writes[0].path,'/api/daily-reports');
    assert.equal(writes[0].body.originalAmount,123.45);
    assert.equal(writes[0].body.partyId,'p1');
    await goto('daily-purchase-analysis');
    await page.getByRole('region',{name:'采购统计分析结果',exact:true}).waitFor();
    assert.equal(await page.getByRole('heading',{name:'供应商排名（前10）',exact:true}).count(),1);
    await page.setViewportSize({width:1440,height:1100});
    await goto('daily-reconciliation');
    await page.locator('.dr-recon-grid').waitFor();
    assert.match(await page.locator('.dr-recon-scope-note').innerText(),/尚不包含按自然月逐日核对明细/);
    const difference = page.locator('.dr-recon-card').filter({hasText:'销售月/年差额'});
    assert.match(await difference.innerText(),/月累计差额（截至所选日期）/);
    assert.match(await difference.innerText(),/10,864.00/);
    assert.match(await difference.innerText(),/9,000.00/);
    assert.match(await difference.innerText(),/1,864.00/);
    await screenshot({path:`${evidence}/reconciliation-desktop.png`,fullPage:true});
    completeReconciliation = false;
    await goto('daily-reconciliation');
    await page.locator('.dr-recon-grid').waitFor();
    assert.match(await difference.innerText(),/数据不完整/);
    assert.match(await difference.innerText(),/待判定/);
    assert.doesNotMatch(await difference.innerText(),/1,864.00/);
    await screenshot({path:`${evidence}/reconciliation-incomplete.png`,fullPage:true});
    access = {...access,canWrite:false,canManage:false};
    await goto('daily-sales');
    await page.getByRole('region',{name:'销售日报明细表',exact:true}).waitFor();
    assert.equal(await page.getByRole('button',{name:'新增销售日报',exact:true}).count(),0);
    assert.equal(await page.getByRole('button',{name:'导入往期销售日报',exact:true}).count(),0);
    const scoped = requests.filter(r => r.path === '/api/daily-reports/analysis');
    assert.ok(scoped.length > 3);
    assert.ok(scoped.every(r => r.headers['x-tenant-id'] === user.tenantId && r.headers['x-organization-id'] === user.organizationId && r.headers['x-account-id'] === user.accountId));
    assert.equal(requests.some(r => /sync|refresh-mock/.test(r.path)),false);
    assert.deepEqual(errors,[]);
  } finally { await browser.close(); await server.close(); }
});
